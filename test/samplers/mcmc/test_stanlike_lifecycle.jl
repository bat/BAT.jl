const TARGET = BAT.batmeasure(MvNormal([0.0], ones(1, 1)))

new_context(seed; visualizer=BATVisualizer()) =
    BATContext(rng=Philox4x((seed, 2841)), ad=ForwardDiff, visualizer=visualizer)

function algorithm(tuning; kwargs...)
    defaults = (
        proposal=RandomWalk(proposaldist=Normal(0, 0.1)),
        proposal_tuning=NoMCMCProposalTuning(),
        adaptive_transform=BAT.TriangularAffineTransform(init=BAT.UnitTransformInit()),
        transform_tuning=tuning,
        pretransform=DoNotTransform(),
        nchains=1, nwalkers=1, nsteps=12, nonzero_weights=false,
        init=MCMCRetryInit(nsteps_init=12),
        burnin=MCMCMultiCycleBurnin(max_ncycles=0, nsteps_final=0),
        convergence=AssumeConvergence(), strict=false,
    )
    TransformedMCMC(; merge(defaults, (; kwargs...))...)
end

function state_fixture(alg; seed=2810)
    state = BAT.MCMCState(alg, TARGET, 1, [[0.125]], new_context(seed))
    BAT.next_cycle!(state)
    return state
end

metric(f) = Matrix(f.A * f.A')

# Recover the ordered selected states from real repetition-weighted output.
# Zero-weight rejected proposals do not enter the adaptation population.
function repeated_rows(samples; cycle=nothing)
    rows = Vector{Float64}[]
    for sample in samples
        !isnothing(cycle) && sample.info.chaincycle != cycle && continue
        @test sample.weight >= 0 && isinteger(sample.weight)
        for _ in 1:Int(sample.weight)
            push!(rows, Vector(sample.v))
        end
    end
    return rows
end

# An independent exact batch oracle for the finite Float64 states actually
# generated by the sampler, rather than a second online accumulator.
function batch_covariance(rows)
    n = length(rows)
    n >= 2 || error("The covariance oracle needs at least two generated rows")
    xs = [Rational{BigInt}.(row) for row in rows]
    d = length(first(xs))
    center = [sum(x[j] for x in xs) / n for j in 1:d]
    scatter = [sum((x[i] - center[i]) * (x[j] - center[j]) for x in xs)
        for i in 1:d, j in 1:d]
    return Float64.(scatter ./ (n - 1))
end

function tuner_snapshot(tuner)
    p = tuner.stats.param_stats
    return (i=tuner.i, start=tuner.window_start, stop=tuner.window_end,
        splits=copy(tuner.window_splits), n=p.cov.n, sum_w=p.cov.sum_w,
        sum_w2=p.cov.sum_w2, mean=collect(p.mean), center=copy(p.cov.Mean_X),
        scatter=copy(p.cov.S), minimum=copy(p.minimum), maximum=copy(p.maximum),
        mode=copy(tuner.stats.mode))
end

function rng_continuation(state)
    chain = state.chain_state
    return (chain=rand(copy(BAT.get_rng(chain.context)), UInt64, 8),
        walkers=[rand(copy(BAT.get_rng(ctx)), UInt64, 8) for ctx in chain.walker_genctxs])
end

function run_chunks(alg, chunks; seed=2810, horizon=12)
    state = state_fixture(alg; seed=seed)
    # H=0 is an established HMC initialization path.
    BAT.mcmc_tuning_init!!(state, 0)
    @test state.trafo_tuner_state.window_end == 0
    BAT.mcmc_tuning_reinit!!(state, horizon)
    output = BAT._empty_chain_outputs(state)
    for n in chunks
        state = BAT.mcmc_iterate!!(output, state; max_nsteps=n, nonzero_weights=false)
    end
    return state, output
end

struct InitSegmentBackend <: BAT.BATVisBackend end
BAT.capture_visualizer_init(::BATVisualizer{InitSegmentBackend}) = true
function BAT.begin_visualizer_init_segment(::BATVisualizer{InitSegmentBackend}, chain, output)
    (cycle=chain.info.cycle, step=chain.stepno)
end
function BAT.end_visualizer_init_segment!(
    vis::BATVisualizer{InitSegmentBackend}, before, chain, output,
)
    lock(vis.content.lock) do
        push!(vis.content.records, (before=before, cycle=chain.info.cycle,
            step=chain.stepno, output=deepcopy(output), metric=metric(chain.f_transform)))
    end
    return nothing
end
segment_visualizer() = BATVisualizer(InitSegmentBackend(),
    (records=NamedTuple[], lock=ReentrantLock()))

# These specialize only fixture-owned initialization algorithms.
struct FixedInitialPoint <: InitvalAlgorithm end
BAT.bat_initval_impl(::BAT.MeasureLike, ::FixedInitialPoint, ::BATContext) =
    (result=[0.125],)

mutable struct RerollInitialPoint <: InitvalAlgorithm
    calls::Int
end
function BAT.bat_initval_impl(::BAT.MeasureLike, init::RerollInitialPoint, ::BATContext)
    init.calls += 1
    return (result=[init.calls == 1 ? 10.5 : 0.5],)
end

unexpected_init_callback(args...) = error("Initialization called the public callback")

# A component is allowed to return a different concrete tuner state through
# the !! protocol. These methods specialize only fixture-owned types.
struct ReplacementTuning <: MCMCTransformTuning
    id::Int
end
struct ReplacementBefore <: BAT.MCMCTransformTunerState
    id::Int
end
mutable struct ReplacementAfter <: BAT.MCMCTransformTunerState
    id::Int
    step::Int
end
BAT.create_trafo_tuner_state(
    tuning::ReplacementTuning, ::BAT.MCMCChainState, ::Integer,
) = ReplacementBefore(tuning.id)
function BAT.mcmc_tune_trafo_post_step!!(
    transform::Function, tuner::ReplacementBefore, chain::BAT.MCMCChainState,
    ::BAT.MCMCProposalState, ::NamedTuple, ::NamedTuple, ::BAT.MCMCStepInfo,
)
    return transform, ReplacementAfter(tuner.id, chain.stepno), chain
end

@testset "StanLike generated lifecycle" begin
    @testset "MultiTrafo stores homogeneous and mixed component states" begin
        for tunings in ((BAT.StanLikeTuning(), BAT.StanLikeTuning()),
            (RAMTuning(), RAMTuning()),
            (BAT.StanLikeTuning(), NoMCMCTransformTuning()),
            (BAT.StanLikeTuning(),))
            adaptive = AdaptiveTransformChain(Tuple(
                BAT.TriangularAffineTransform(init=BAT.UnitTransformInit()) for _ in tunings))
            state = state_fixture(algorithm(MultiTrafoTuning(tunings); adaptive_transform=adaptive))
            children = state.trafo_tuner_state.trafo_tuners
            @test length(children) == length(tunings)
            @test eltype(children) === BAT.MCMCTransformTunerState
            # A child may return a different state type through the !! hooks.
            sibling = length(children) > 1 ? children[2] : nothing
            replacement = BAT.FrozenMCMCTransformTunerState()
            children[1] = replacement
            @test children[1] === replacement
            @test length(children) == 1 || children[2] === sibling
        end
    end

    @testset "default homogeneous RAM components generate real transitions" begin
        adaptive = AdaptiveTransformChain((
            BAT.TriangularAffineTransform(init=BAT.UnitTransformInit()),
            BAT.TriangularAffineTransform(init=BAT.UnitTransformInit()),
        ))
        # Deliberately omit transform_tuning to exercise the public default.
        alg = TransformedMCMC(proposal=RandomWalk(proposaldist=Normal(0, 0.1)),
            adaptive_transform=adaptive, pretransform=DoNotTransform(),
            nchains=1, nwalkers=1, nsteps=4,
            init=MCMCRetryInit(nsteps_init=4),
            burnin=MCMCMultiCycleBurnin(max_ncycles=0, nsteps_final=0),
            convergence=AssumeConvergence(), strict=false)
        @test alg.transform_tuning isa MultiTrafoTuning
        @test all(t -> t isa RAMTuning, alg.transform_tuning.trafo_tunings)
        state = state_fixture(alg; seed=2817)
        multi = state.trafo_tuner_state
        @test eltype(multi.trafo_tuners) === BAT.MCMCTransformTunerState
        @test multi.trafo_tuners[1] !== multi.trafo_tuners[2]
        BAT.mcmc_tuning_init!!(state, 4)
        for step in 1:2
            previous = state.chain_state.f_transform
            state = BAT.mcmc_step!!(state)
            @test state.chain_state.stepno == step
            @test state.trafo_tuner_state === multi
            @test all(t -> t isa BAT.RAMTrafoTunerState && t.nsteps == step,
                multi.trafo_tuners)
            @test state.chain_state.f_transform !== previous
            @test !multi.last_change_restarts
            for pair in (state.chain_state.current, state.chain_state.proposed)
                @test state.chain_state.f_transform.(pair.z.v) ≈ pair.x.v
                @test all(isfinite, pair.x.logd)
                @test all(isfinite, pair.z.logd)
            end
        end
    end

    @testset "actual post-step hooks replace homogeneous and mixed child types" begin
        for tunings in ((ReplacementTuning(11), ReplacementTuning(22)),
            (ReplacementTuning(11), NoMCMCTransformTuning()))
