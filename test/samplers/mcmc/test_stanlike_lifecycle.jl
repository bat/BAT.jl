            @test !multi.last_change_restarts
        end
    end

    @testset "MH and HMC continuation is independent of iterator chunking" begin
        tuning = BAT.StanLikeTuning(init_buffer=0, term_buffer=1, window_size=4)
        for proposal in (RandomWalk(proposaldist=Normal(0, 0.1)),
            HamiltonianMC(step_size=0.15, max_depth=2))
            @testset "$(nameof(typeof(proposal)))" begin
                alg = algorithm(tuning; proposal=proposal)
                whole, whole_output = run_chunks(alg, (12,))
                chunked, chunked_output = run_chunks(alg, (2, 3, 7))
                whole_rows = repeated_rows(only(whole_output))
                chunked_rows = repeated_rows(only(chunked_output))
                @test length(whole_rows) == 12
                @test whole_rows == chunked_rows
                @test whole.chain_state.current == chunked.chain_state.current
                @test whole.chain_state.proposed == chunked.chain_state.proposed
                @test rng_continuation(whole) == rng_continuation(chunked)
                @test isequal(tuner_snapshot(whole.trafo_tuner_state),
                    tuner_snapshot(chunked.trafo_tuner_state))
                @test whole.trafo_tuner_state.window_splits == [10]
                @test whole.trafo_tuner_state.i == 10
                @test whole.trafo_tuner_state.stats.param_stats.cov.n == 0
                expected = batch_covariance(whole_rows[1:10])
                @test only(expected) > 0
                @test metric(whole.chain_state.f_transform) ≈ expected rtol=1e-9 atol=1e-14
                @test metric(chunked.chain_state.f_transform) ≈ expected rtol=1e-9 atol=1e-14

                # Extra numerical work continues, but the completed campaign
                # neither collects rows nor installs another transform.
                old_transform = chunked.chain_state.f_transform
                chunked = BAT.mcmc_iterate!!(chunked_output, chunked;
                    max_nsteps=3, nonzero_weights=false)
                @test chunked.chain_state.stepno == 15
                @test chunked.trafo_tuner_state.i == 10
                @test chunked.trafo_tuner_state.stats.param_stats.cov.n == 0
                @test chunked.chain_state.f_transform === old_transform
            end
        end
    end

